// Copies the core types UI plugins see (event payloads) out of the app's
// generated bindings (`just bindings`) into src/core.ts, with every type
// they depend on. `--check` fails when src/core.ts is out of date.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const bindings = fileURLToPath(
  new URL("../../../apps/desktop/src/api/bindings.ts", import.meta.url),
);
const target = fileURLToPath(new URL("../src/core.ts", import.meta.url));
/** Payload types of the events in PluginEventName. */
const roots = [
  "GameStarted_Serialize",
  "GameExited_Serialize",
  "LibraryChanged_Serialize",
  "SettingsChanged",
  "PluginDisabled",
  "PluginsChanged",
  "PluginReloaded_Serialize",
];

/** `export type Name = …;` blocks, with the doc comment right above each. */
function declarations(source) {
  const found = new Map();
  const pattern =
    /((?:\/\*\*[\s\S]*?\*\/\n)?)export type (\w+)\b[\s\S]*?;\n(?=\n|\/\*\*|export|$)/g;
  for (const match of source.matchAll(pattern)) found.set(match[2], match[0]);
  return found;
}

export function render() {
  const all = declarations(readFileSync(bindings, "utf8"));
  const wanted = [];
  const pending = [...roots];
  while (pending.length) {
    const name = pending.shift();
    if (wanted.includes(name)) continue;
    const text = all.get(name);
    if (!text) throw new Error(`${name} is not in the generated bindings`);
    wanted.push(name);
    for (const [, used] of text.replace(/\/\*\*[\s\S]*?\*\//g, "").matchAll(/\b([A-Z]\w*)\b/g))
      if (all.has(used) && used !== name) pending.push(used);
  }
  const header =
    "// Generated by `pnpm --filter @caskade/sdk core-types` from the app's\n" +
    "// bindings (apps/desktop/src/api/bindings.ts). Do not edit.";
  const blocks = wanted.sort().map((name) => all.get(name).trimEnd());
  return `${[header, ...blocks].join("\n\n")}\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = render();
  if (process.argv.includes("--check")) {
    if (readFileSync(target, "utf8") !== text) {
      console.error("src/core.ts is out of date: run `pnpm --filter @caskade/sdk core-types`");
      process.exit(1);
    }
  } else writeFileSync(target, text);
}
