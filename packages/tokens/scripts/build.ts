// Compiles tokens/*.json into tokens.css and manifest.json, and the token
// tables in docs/theming/tokens.md. `--check` fails when they're stale.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { compile, type ManifestEntry, setFromJson, tiers } from "../src/compile.ts";

const root = fileURLToPath(new URL("..", import.meta.url));
const read = (file: string) => JSON.parse(readFileSync(`${root}${file}`, "utf8")) as unknown;

export function build() {
  const files = tiers.map((tier) => ({
    tier,
    file: `tokens/${tier}.json`,
    tree: read(`tokens/${tier}.json`),
  }));
  const sets = readdirSync(`${root}tokens/sets`)
    .filter((name) => name.endsWith(".json"))
    .sort()
    .map((name) =>
      setFromJson(name.replace(/\.json$/, ""), `tokens/sets/${name}`, read(`tokens/sets/${name}`)),
    );
  const { css, manifest } = compile(files, sets);
  return {
    [`${root}tokens.css`]: css,
    [`${root}manifest.json`]: `${JSON.stringify(manifest, null, 2)}\n`,
    [`${root}../../docs/theming/tokens.md`]: docs(
      manifest,
      sets.map((set) => set.name),
    ),
  };
}

function docs(manifest: ManifestEntry[], sets: string[]) {
  const cell = (text: string) => text.replaceAll("|", "\\|");
  const lines = [
    "# Design tokens",
    "",
    "Generated by `pnpm --filter @caskade/tokens build` from `packages/tokens/tokens/`. Do not edit.",
    "",
    "Every token is a CSS custom property. Themes set them in `tokens.json`; see",
    "[the theming contract](README.md). Override sets: " +
      sets.map((set) => `\`${set}\``).join(", ") +
      ".",
  ];
  for (const tier of tiers) {
    lines.push(
      "",
      `## ${tier[0]?.toUpperCase()}${tier.slice(1)}`,
      "",
      "| Token | Type | Default | Description |",
      "| --- | --- | --- | --- |",
    );
    for (const entry of manifest.filter((token) => token.tier === tier))
      lines.push(
        `| \`${entry.name}\` | ${entry.type} | \`${cell(entry.resolved)}\` | ${cell(entry.description ?? "")} |`,
      );
  }
  return `${lines.join("\n")}\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const outputs = build();
  const stale = Object.entries(outputs).filter(([file, text]) => {
    try {
      return readFileSync(file, "utf8") !== text;
    } catch {
      return true;
    }
  });
  if (process.argv.includes("--check")) {
    if (stale.length) {
      console.error(
        `Stale: ${stale.map(([file]) => file.replace(root, "")).join(", ")}. Run \`pnpm --filter @caskade/tokens build\`.`,
      );
      process.exit(1);
    }
  } else for (const [file, text] of stale) writeFileSync(file, text);
}
