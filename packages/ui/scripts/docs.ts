/** Writes docs/theming/anatomy.md and anatomy.json (the contract the core's
 * theme lint checks selectors against) from the anatomy catalogue; `--check`
 * fails when either is stale. Run with `node scripts/docs.ts`. */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { type AnatomyEntry, anatomy, contractAttributes } from "../src/anatomy.ts";

const docs = fileURLToPath(new URL("../../../docs/theming/anatomy.md", import.meta.url));
const json = fileURLToPath(new URL("../anatomy.json", import.meta.url));

const code = (text: string) => `\`${text}\``;
const cell = (text: string) => text.replaceAll("|", "\\|").replaceAll("\n", " ");

function section(name: string, entry: AnatomyEntry): string[] {
  const appOnly = new Set(entry.appOnly ?? []);
  const mark = (key: string) => (appOnly.has(key) ? " (app only)" : "");
  const lines = [
    `## ${code(name)}`,
    "",
    `${entry.description} Rendered by ${entry.rendered}.`,
    "",
    `Root: ${code(`[data-cs="${name}"]`)}`,
    "",
  ];
  const parts = Object.entries(entry.parts);
  if (parts.length) {
    lines.push("| Part | Selector | What it is |", "| --- | --- | --- |");
    for (const [part, what] of parts)
      lines.push(
        `| ${code(part)}${mark(part)} | ${code(`[data-cs="${name}"] [data-part="${part}"]`)} | ${cell(what)} |`,
      );
    lines.push("");
  }
  if (entry.slots?.length)
    lines.push(
      `Slots: ${entry.slots.map(code).join(", ")} hold the caller's content; parts inside them belong to that content.`,
      "",
    );
  if (entry.container)
    lines.push("Container: its content comes from the caller, which may add parts of its own.", "");
  const states = Object.entries(entry.states);
  if (states.length) {
    lines.push("State on the root:", "");
    for (const [attribute, values] of states)
      lines.push(`- ${code(attribute)}${mark(attribute)}: ${values.map(code).join(", ")}`);
    lines.push("");
  }
  if (entry.interaction.length)
    lines.push(`React Aria interaction: ${entry.interaction.map(code).join(", ")}`, "");
  if (entry.contains?.length)
    lines.push(
      `Contains: ${entry.contains.map((inner) => `[${code(inner)}](#${inner})`).join(", ")}`,
      "",
    );
  return lines;
}

export function build(): string {
  const entries = Object.entries(anatomy) as [string, AnatomyEntry][];
  const group = (source: AnatomyEntry["source"]) =>
    entries.filter(([, entry]) => entry.source === source);
  const index = (list: [string, AnatomyEntry][]) =>
    list.map(([name, entry]) => `- [${code(name)}](#${name}): ${entry.description}`);
  const lines = [
    "<!-- Generated by @caskade/ui from packages/ui/src/anatomy.ts (pnpm --filter @caskade/ui docs). Do not edit. -->",
    "",
    "# Anatomy catalogue",
    "",
    "The selectors a theme or plugin may target (see [README](README.md)). Each",
    'component renders `data-cs="<name>"` on its root and `data-part="<part>"` on',
    "its parts. A part belongs to the nearest enclosing root, so",
    '`[data-cs="game-card"] [data-part="title"]` does not match a title inside a',
    "nested component. A nested component's root can also be a part of its",
    'parent: a card\'s art is `[data-cs="game-art"][data-part="art"]`.',
    "",
    "Domain state is an attribute on the root, such as `data-status` or",
    "`data-variant`. Interaction state comes from React Aria",
    "(`data-hovered`, `data-pressed`, `data-focus-visible`, `data-selected`,",
    "`data-disabled`, …). Class names are not API and change without notice.",
    "",
    "Parts and states marked (app only) are rendered only by the app's own",
    "variant of the component, such as the library's card.",
    "",
    "## `@caskade/ui` components",
    "",
    ...index(group("@caskade/ui")),
    "",
    "## App shell",
    "",
    ...index(group("app")),
    "",
    ...entries.flatMap(([name, entry]) => section(name, entry)),
  ];
  return `${lines.join("\n").trimEnd()}\n`;
}

/** The catalogue as data: roots with their parts, states and interaction,
 * and every attribute a selector may use. */
export function contract(): string {
  const entries = Object.entries(anatomy) as [string, AnatomyEntry][];
  const attributes = new Set<string>([
    "data-cs",
    "data-part",
    ...contractAttributes.root,
    ...contractAttributes.parts,
  ]);
  const roots = Object.fromEntries(
    entries.map(([name, entry]) => {
      for (const attribute of [...Object.keys(entry.states), ...entry.interaction])
        attributes.add(attribute);
      return [
        name,
        {
          parts: Object.keys(entry.parts),
          states: entry.states,
          interaction: entry.interaction,
        },
      ];
    }),
  );
  return `${JSON.stringify({ roots, attributes: [...attributes].sort() }, null, 2)}\n`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const outputs = [
    [docs, build()],
    [json, contract()],
  ] as const;
  if (process.argv.includes("--check")) {
    for (const [file, text] of outputs) {
      let current = "";
      try {
        current = readFileSync(file, "utf8");
      } catch {}
      if (current !== text) {
        console.error(`${file} is stale: run pnpm --filter @caskade/ui docs`);
        process.exit(1);
      }
    }
  } else for (const [file, text] of outputs) writeFileSync(file, text);
}
