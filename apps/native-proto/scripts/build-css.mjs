// Compiles the prototype's stylesheet with the app's own Tailwind entry
// (apps/desktop/src/styles/index.css: tokens, base, utilities) and the default
// theme, scanning only the prototype's Rust sources for class names.
//
//   node apps/native-proto/scripts/build-css.mjs   (after `pnpm install`)
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const proto = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const repo = path.resolve(proto, "../..");
const desktop = path.join(repo, "apps/desktop");
const fromDesktop = createRequire(path.join(desktop, "package.json"));
const fromVite = createRequire(fromDesktop.resolve("@tailwindcss/vite"));
const { compile } = await import(fromVite.resolve("@tailwindcss/node"));
const { Scanner } = fromVite("@tailwindcss/oxide");

const styles = path.join(desktop, "src/styles");
// The app's entry, minus its @source of packages/ui (the prototype has its own markup).
const entry = readFileSync(path.join(styles, "index.css"), "utf8").replace(/^@source .*$/m, "");
const theme = readFileSync(path.join(repo, "themes/default/theme.css"), "utf8");
const input = `${entry}
@source "${path.join(proto, "src")}";
@layer cs.theme {
${theme}
}
/* Blitz registers the bundled variable fonts under their own family names. */
@layer cs.user {
  :root {
    --cs-font-sans: "Inter", ui-sans-serif, sans-serif;
    --cs-font-display: "Oxanium", "Inter", ui-sans-serif, sans-serif;
    --cs-font-mono: "JetBrains Mono", ui-monospace, monospace;
  }
}
`;

const compiler = await compile(input, { base: styles, onDependency: () => {} });
const sources = compiler.sources.filter((s) => !s.base.includes("packages/ui"));
const scanner = new Scanner({ sources });
const css = compiler.build(scanner.scan());
const out = path.join(proto, "assets/app.css");
writeFileSync(out, `/* Generated by scripts/build-css.mjs: do not edit. */\n${css}`);
console.log(`${out}: ${css.length} bytes, ${scanner.files.length} files scanned`);
