/// `apps/desktop/src/api/bindings.ts`.
pub fn default_path() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../src/api/bindings.ts")
}

/// The bindings as TypeScript source.
pub fn render() -> Result<String, String> {
    let temp = std::env::temp_dir().join(format!("caskade-bindings-{}.ts", std::process::id()));
    export(&temp)?;
    let text = std::fs::read_to_string(&temp).map_err(|error| error.to_string());
    let _ = std::fs::remove_file(&temp);
    text
}

pub fn export(path: &Path) -> Result<(), String> {
    builder()
        .export(
            specta_typescript::Typescript::default()
                .header("// Generated by `just bindings` (tauri-specta). Do not edit.\n/* eslint-disable */\n// @ts-nocheck\n"),
            path,
        )
        .map_err(|error| error.to_string())
}
