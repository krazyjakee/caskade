// Compiles the native app's stylesheet (#90) from the webview's own Tailwind
// entry, apps/desktop/src/styles/index.css (the layer order, @caskade/tokens,
// base and Tailwind 4's utilities), scanning the native app's Rust sources
// for class names instead of packages/ui. Themes and user CSS aren't in it:
// the app adds them at run time, as the webview does.
//
//   node apps/native/scripts/build-css.mjs           writes assets/app.css and src/shots/shots.css
//   node apps/native/scripts/build-css.mjs --check   fails when either is stale
//
// After `pnpm install`.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const native = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const repo = path.resolve(native, "../..");
const desktop = path.join(repo, "apps/desktop");
const fromDesktop = createRequire(path.join(desktop, "package.json"));
const fromVite = createRequire(fromDesktop.resolve("@tailwindcss/vite"));
const { compile } = await import(fromVite.resolve("@tailwindcss/node"));
const { Scanner } = fromVite("@tailwindcss/oxide");

const styles = path.join(desktop, "src/styles");
const entry = readFileSync(path.join(styles, "index.css"), "utf8");
if (!/^@source .*packages\/ui\/src.*$/m.test(entry)) {
  throw new Error("index.css no longer names packages/ui in @source: update build-css.mjs");
}
// The webview's markup isn't the native app's: scan apps/native/src instead.
// The app's sheet leaves out the screenshot harness's reference screens
// (src/shots, dev only); the harness's own sheet (src/shots/shots.css) is
// the same entry over everything, screens included.
const relative = (folder) => path.relative(styles, folder).split(path.sep).join("/");
const source = (exclude) =>
  `@source "${relative(path.join(native, "src"))}";${
    exclude ? `\n@source not "${relative(path.join(native, "src/shots"))}";` : ""
  }`;
const outputs = [
  [path.join(native, "assets/app.css"), true],
  [path.join(native, "src/shots/shots.css"), false],
];

let stale = false;
for (const [out, exclude] of outputs) {
  const input = entry.replace(/^@source .*packages\/ui\/src.*$/m, source(exclude));
  const compiler = await compile(input, { base: styles, onDependency: () => {} });
  const scanner = new Scanner({ sources: compiler.sources });
  const css = `/* Generated by apps/native/scripts/build-css.mjs: do not edit. */\n${compiler.build(scanner.scan())}`;
  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(out, "utf8");
    } catch {}
    if (current !== css) {
      console.error(`${out} is stale: run node apps/native/scripts/build-css.mjs`);
      stale = true;
    }
  } else {
    writeFileSync(out, css);
    console.log(
      `${path.relative(repo, out)}: ${css.length} bytes, ${scanner.files.length} files scanned`,
    );
  }
}
if (stale) process.exit(1);
