// Compiles the native app's stylesheet (#90) from its Tailwind entry,
// apps/native/styles/index.css (the layer order, @caskade/tokens, base and
// Tailwind 4's utilities), scanning the app's Rust sources for class names.
// Themes and user CSS aren't in it: the app adds them at run time.
//
//   node apps/native/scripts/build-css.mjs           writes assets/app.css and src/shots/shots.css
//   node apps/native/scripts/build-css.mjs --check   fails when either is stale
//
// After `pnpm install` (Tailwind is apps/native/package.json's).
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const native = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const repo = path.resolve(native, "../..");
const fromNative = createRequire(path.join(native, "package.json"));
const { compile } = await import(fromNative.resolve("@tailwindcss/node"));
const { Scanner } = fromNative("@tailwindcss/oxide");

const styles = path.join(native, "styles");
const entry = readFileSync(path.join(styles, "index.css"), "utf8");
const scan = /^@source "\.\.\/src";$/m;
if (!scan.test(entry)) {
  throw new Error('index.css no longer has @source "../src": update build-css.mjs');
}
// The app's sheet leaves out the screenshot harness's reference screens
// and the component gallery (src/shots, src/gallery: dev only); the
// harness's own sheet (src/shots/shots.css, the gallery's too) is the same
// entry over everything, screens included.
const relative = (folder) => path.relative(styles, folder).split(path.sep).join("/");
const source = (exclude) =>
  `@source "${relative(path.join(native, "src"))}";${
    exclude
      ? ["src/shots", "src/gallery"]
          .map((dev) => `\n@source not "${relative(path.join(native, dev))}";`)
          .join("")
      : ""
  }`;
const outputs = [
  [path.join(native, "assets/app.css"), true],
  [path.join(native, "src/shots/shots.css"), false],
];

let stale = false;
for (const [out, exclude] of outputs) {
  const input = entry.replace(scan, source(exclude));
  const compiler = await compile(input, { base: styles, onDependency: () => {} });
  const scanner = new Scanner({ sources: compiler.sources });
  const css = `/* Generated by apps/native/scripts/build-css.mjs: do not edit. */\n${compiler.build(scanner.scan())}`;
  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(out, "utf8");
    } catch {}
    if (current !== css) {
      console.error(`${out} is stale: run node apps/native/scripts/build-css.mjs`);
      stale = true;
    }
  } else {
    writeFileSync(out, css);
    console.log(
      `${path.relative(repo, out)}: ${css.length} bytes, ${scanner.files.length} files scanned`,
    );
  }
}
if (stale) process.exit(1);
