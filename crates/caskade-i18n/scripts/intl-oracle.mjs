// Writes `src/intl_oracle.rs`: what the browser's `Intl` shows for the
// native UI's formatting (`src/intl.rs`), as the webview's
// `presentation.ts` asks for it, in each language with data there. Run
// with Node from the repository root when the formatting or a language
// changes:
//
//   node crates/caskade-i18n/scripts/intl-oracle.mjs
//
// Its expectations are Node's ICU (printed in the file's header).
import { writeFileSync } from "node:fs";

const locales = ["en-US", "en-GB", "sv"];
const rust = (value) =>
  `"${[...value]
    .map((c) =>
      c === '"' || c === "\\"
        ? `\\${c}`
        : c.charCodeAt(0) > 126
          ? `\\u{${c.codePointAt(0).toString(16)}}`
          : c,
    )
    .join("")}"`;

const n = (locale, value, options) => new Intl.NumberFormat(locale, options).format(value);
const d = (locale, ms, options) =>
  new Intl.DateTimeFormat(locale, { timeZone: "UTC", ...options }).format(ms);

const cases = [];
const add = (call, expected) => cases.push(`    check!(${call}, ${rust(expected)});`);

for (const locale of locales) {
  const l = rust(locale);
  for (const value of [0, 7, 42.5, 999.9995, 1234, -1234.5, 1234567.891, 0.0004]) {
    add(`count(${l}, ${value}_f64)`, n(locale, value));
  }
  for (const value of [0, 42, 99.6, 100]) {
    add(
      `percent(${l}, ${value}_f64)`,
      n(locale, value / 100, { style: "percent", maximumFractionDigits: 0 }),
    );
  }
  const units = ["kilobyte", "megabyte", "gigabyte", "terabyte", "petabyte"];
  for (const bytes of [0, 512, 1536, 1048575, 1610612736, 5e12, 2 ** 60]) {
    let value = Math.max(0, bytes) / 1024;
    let unit = 0;
    while (value >= 1024 && unit < units.length - 1) {
      value /= 1024;
      unit++;
    }
    const expected = n(locale, value, {
      style: "unit",
      unit: units[unit],
      unitDisplay: "short",
      minimumFractionDigits: 1,
      maximumFractionDigits: 1,
    });
    add(`size(${l}, ${bytes}_u64)`, expected);
  }
  const narrow = (value, unit, digits = 0) =>
    n(locale, value, {
      style: "unit",
      unit,
      unitDisplay: "narrow",
      minimumFractionDigits: digits,
      maximumFractionDigits: digits,
    });
  add(`duration(${l}, 0).unwrap()`, narrow(0, "minute"));
  add(`one_minute(${l})`, narrow(1, "minute"));
  for (const seconds of [60, 2520, 3599, 3600, 12600, 360000]) {
    const expected =
      seconds < 3600
        ? narrow(Math.floor(seconds / 60), "minute")
        : narrow(Math.round(seconds / 360) / 10, "hour", 1);
    add(`duration(${l}, ${seconds}).unwrap()`, expected);
  }
  for (const [year, month, day, hour, minute, second] of [
    [2026, 10, 28, 14, 5, 9],
    [2026, 1, 3, 0, 5, 0],
    [2026, 9, 30, 12, 0, 59],
    [1999, 12, 31, 23, 59, 1],
  ]) {
    const ms = Date.UTC(year, month - 1, day, hour, minute, second);
    const at = `DateTime { year: ${year}, month: ${month}, day: ${day}, hour: ${hour}, minute: ${minute}, second: ${second} }`;
    add(`day(${l}, ${at})`, d(locale, ms, { dateStyle: "medium" }));
    add(`date_time(${l}, ${at})`, d(locale, ms, { dateStyle: "medium", timeStyle: "short" }));
    add(`month(${l}, ${year}, ${month})`, d(locale, ms, { month: "short", year: "numeric" }));
    const hm = { hour: "2-digit", minute: "2-digit" };
    add(`time(${l}, ${at}, Clock::System, false)`, d(locale, ms, hm));
    add(`time(${l}, ${at}, Clock::System, true)`, d(locale, ms, { ...hm, second: "2-digit" }));
    add(`time(${l}, ${at}, Clock::H12, false)`, d(locale, ms, { ...hm, hour12: true }));
    add(`time(${l}, ${at}, Clock::H23, false)`, d(locale, ms, { ...hm, hourCycle: "h23" }));
  }
  const relative = new Intl.RelativeTimeFormat(locale, { numeric: "auto" });
  for (const days of [0, 1, 2, 13, 14, 20, 59]) {
    const text = days < 14 ? relative.format(-days, "day") : relative.format(-Math.floor(days / 7), "week");
    add(`relative_day(${l}, ${days}, false).unwrap()`, text);
    add(
      `relative_day(${l}, ${days}, true).unwrap()`,
      text.charAt(0).toLocaleUpperCase(locale) + text.slice(1),
    );
  }
}

// The Language setting's choices: each language by its own name.
for (const tag of ["en", "en-GB", "en-US", "en-XA", "sv"]) {
  const name = new Intl.DisplayNames([tag], { type: "language" }).of(tag);
  add(`language_name(${JSON.stringify(tag)}).unwrap()`, name.charAt(0).toLocaleUpperCase(tag) + name.slice(1));
}

const file = `// Generated by scripts/intl-oracle.mjs from Node ${process.versions.node}'s Intl
// (ICU ${process.versions.icu}): don't edit; run the script again.

use super::*;

#[test]
#[rustfmt::skip]
fn matches_intl() {
    let mut wrong = Vec::new();
    macro_rules! check {
        ($call:expr, $expected:expr) => {
            let got = $call;
            if got != $expected {
                wrong.push(format!("{}: {got:?}, Intl says {:?}", stringify!($call), $expected));
            }
        };
    }
${cases.join("\n")}
    assert!(wrong.is_empty(), "{} of ${cases.length} differ:\n{}", wrong.len(), wrong.join("\n"));
}
`;
writeFileSync(new URL("../src/intl_oracle.rs", import.meta.url), file);
console.log(`${cases.length} cases`);
